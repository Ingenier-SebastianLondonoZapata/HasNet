CREATE TABLE IF NOT EXISTS bdSoportesMercantiles (
    idSoporte INT(11) NOT NULL AUTO_INCREMENT,
    cufe VARCHAR(200) NOT NULL,
    prefijo VARCHAR(20) NULL,
    folio VARCHAR(40) NULL,
    nitEmisor VARCHAR(30) NULL,
    nombreEmisor VARCHAR(255) NULL,
    fechaEmision DATE NULL,
    total DECIMAL(18,2) NULL,
    evento VARCHAR(40) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    descripcion VARCHAR(500) NULL,
    errores LONGTEXT NULL,
    uuidEvento VARCHAR(200) NULL,
    fechaEvento VARCHAR(40) NULL,
    origen VARCHAR(20) NULL,
    archivo VARCHAR(255) NULL,
    usuario VARCHAR(100) NULL,
    fechaRegistro DATETIME NOT NULL,
    PRIMARY KEY (idSoporte),
    KEY idx_soportes_cufe (cufe),
    KEY idx_soportes_fecha (fechaRegistro),
    KEY idx_soportes_emisor (nitEmisor)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
